# Database Configuration
# We connect directly to our Supabase cloud instance via a single DATABASE_URL string.
# If we are offline or DNS fails, we gracefully degrade to local SQLite so offline developer testing remains 100% resilient! 😄
import dj_database_url
import socket

DATABASE_URL = os.getenv('DATABASE_URL', '')
SUPABASE_DB_HOST = os.getenv('SUPABASE_DB_HOST', '')

import urllib.parse

def check_host_resolves(host):
    if not host:
        return False
    try:
        socket.getaddrinfo(host, None)
        return True
    except socket.gaierror:
        return False

# Determine primary host to check
primary_host = None
if DATABASE_URL:
    try:
        parsed = urllib.parse.urlparse(DATABASE_URL)
        primary_host = parsed.hostname
    except Exception:
        pass
elif SUPABASE_DB_HOST:
    primary_host = SUPABASE_DB_HOST

can_resolve_supabase = check_host_resolves(primary_host)

if not can_resolve_supabase:
    print(f"[NEXA settings.py] WARNING: Cannot resolve DB host '{primary_host}'. Falling back to local SQLite.")

# If a full DATABASE_URL is provided and resolvable
if DATABASE_URL and can_resolve_supabase:
    DATABASES = {
        'default': dj_database_url.config(
            default=DATABASE_URL,
            conn_max_age=600,
            ssl_require=True
        )
    }
    print("[NEXA settings.py] Connected to database via DATABASE_URL string.")
elif SUPABASE_DB_HOST and can_resolve_supabase:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': os.getenv('SUPABASE_DB_NAME', 'postgres'),
            'USER': os.getenv('SUPABASE_DB_USER', 'postgres'),
            'PASSWORD': os.getenv('SUPABASE_DB_PASSWORD', ''),
            'HOST': SUPABASE_DB_HOST,
            'PORT': os.getenv('SUPABASE_DB_PORT', '5432'),
            'OPTIONS': {
                'sslmode': 'require',
            }
        }
    }
    print("[NEXA settings.py] Connected to Supabase via individual connection parameters.")
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
    print("[NEXA settings.py] Running with SQLite local database fallback.")


